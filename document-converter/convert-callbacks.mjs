import fs from "node:fs";
import path from "path";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const __dirname = dirname(fileURLToPath(import.meta.url));

const input = fs.readFileSync(path.join(__dirname, "..", "official-reference-copy", "callbacks.md"), "utf8");

const blocks = input.split(/\n(?=## )/);

const functions = [];

const types = new Set();
const builtinTypes = new Set([
    /*
     * Primitive types
     */
    "string",
    "number",
    "boolean",
    "bigint",
    "symbol",
    "object",
    "unknown",
    "any",
    "never",
    "void",
    "undefined",
    "null",
    "true",
    "false",

    /*
     * Built-in generic types
     */
    "Array",
    "ReadonlyArray",
    "Record",
    "Partial",
    "Required",
    "Pick",
    "Omit",
    "Exclude",
    "Extract",
    "NonNullable",
    "ReturnType",
    "Parameters",
    "ConstructorParameters",
    "InstanceType",
    "ThisType",
    "Promise",
    "Awaited",

    /*
     * Intrinsic string manipulation types.
     */
    "Uppercase",
    "Lowercase",
    "Capitalize",
    "Uncapitalize",
]);

const returnTypeOverrides = {
    playerCommand: "boolean | undefined",
};

for (const block of blocks) {

    const match = block.match(
        /^## ([A-Za-z0-9_]+)\n[\s\S]*?\| Parameter \| Type \| Description \|\n\|[-| ]+\|\n([\s\S]*?)(?=\n\n|$)/
    );

    const returnMatch = block.match(
        /^### Returns:\n`(.+)`/m
    )

    if (!match) continue;

    const [, functionName, parameterTable] = match;

    const params = [];

    for (const line of parameterTable.trim().split("\n")) {
        const columns = line
            .split(/(?<!\\)\|/)
            .map(v => v.trim().replaceAll("`", "").replaceAll("\\", ""))
            .filter(Boolean);

        if (columns.length < 2) continue;

        const [name, type] = columns;

        params.push(`    ${name}: ${type}`);

        type.split(" | ").forEach(
            e => !(
                // String literal
                e.startsWith("\"")
            ) && types.add(
                // Remove array type defenition such as number[]
                e.replaceAll(/\[.*\]/g, "")
            ))
    }
    const returnType = returnTypeOverrides[functionName]
        ? returnTypeOverrides[functionName]
        : returnMatch?.[1].replaceAll("\\", "") ?? "void";
    returnType.split(" | ").forEach(
        e => !(
            // String literal
            e.startsWith("\"")
        ) && types.add(
            // Remove array type defenition such as number[]
            e.replaceAll(/\[.*\]/g, "")
        ))

    functions.push(
        `  var ${functionName}: (\n${params.join(",\n")}\n  ) => ${returnType};`
    );
}

const anyTypeDefenition = [];

for (const type of types) {
    if (type && !builtinTypes.has(type)) {
        let suggestedType;
        if (type.includes("Id")) {
            suggestedType = "string";
        } else if (type.includes("Type")) {
            suggestedType = "string";
        } else {
            suggestedType = "any";
        }
        anyTypeDefenition.push(`type ${type}<T = any> = ${suggestedType};`)
    }
}

const output = `// This file is auto-generated by convert-callbacks.mjs.
export { };

${anyTypeDefenition.join("\n")}

declare global {
${functions.join("\n\n")}
}
`;

fs.writeFileSync(path.join(__dirname, "..", "lib", "callbacks.d.ts"), output);

console.log("Generated ./lib/callbacks.d.ts");
